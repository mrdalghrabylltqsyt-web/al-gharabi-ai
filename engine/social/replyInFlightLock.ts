/**
 * REL-01 — قفل داخل العملية يمنع رد خارجي مكرر فعلي عند تزامن طلبين على نفس
 * الحدث (نفس التعليق/الرسالة على نفس المنصة).
 *
 * الثغرة المُغلَقة (تدقيق جنائي، نتيجة HIGH #7): كل مسارات الرد الخارجي
 * (فيسبوك، إنستغرام، يوتيوب، تيليغرام — تعليق ورسالة) تتبع نمط "تحقق من عدم
 * التكرار ← انتظار شبكي (إرسال فعلي للمزوّد) ← تسجيل الرد في السجل بعد
 * الإرسال". بين لحظة التحقق ولحظة التسجيل يوجد `await` حقيقي (نداء شبكة خارجي)،
 * فإذا وصل طلبان لنفس الحدث الخارجي أثناء هذه النافذة (نقرة مزدوجة من المالك،
 * إعادة محاولة من العميل بعد انقطاع الشبكة، أو تزامن مع دورة مراقبة يوتيوب
 * التلقائية) فكلاهما يتجاوز فحص "هل رُدَّ على هذا من قبل؟" معاً، وكلاهما يُرسل
 * رداً فعلياً خارجياً — رد مكرر حقيقي يراه عميل حقيقي على المنصة.
 *
 * الحل: مفتاح (منصة + نوع الحدث + معرّف خارجي) يُحجز **ذرّياً** قبل أي عمل.
 * الحجز تحقق+إضافة في عبارة متزامنة واحدة بلا `await` بينهما — Node.js لا يُبدّل
 * بين عمليتين متزامنتين (synchronous) لجلستين مختلفتين إلا عند أول `await`، لذا
 * هذا الحجز ذرّي فعلاً ضمن نفس العملية. طلب ثانٍ لنفس المفتاح أثناء تنفيذ الأول
 * يُرفض فوراً (بلا أي إرسال) بدل المخاطرة بتكرار فعلي. المفتاح يُفرَج عنه دائماً
 * من `finally` في المستدعي (نجاحاً أو فشلاً) فلا يبقى محجوزاً أبداً بعد انتهاء
 * الطلب الذي حجزه.
 *
 * حدود الحل (صريحة، غير مُقنَّعة): قفل **داخل العملية فقط** (in-memory)، لا يغطي
 * تعدد نسخ الخادم (عدة عمليات Render متزامنة). هذا يكفي اليوم (نسخة واحدة فعلية
 * على Render حسب التأكيد السابق)، ويُغلق فعلياً كل سباقات التزامن ضمن العملية
 * الواحدة (نقرة مزدوجة، إعادة محاولة، تزامن مراقب/طلب يدوي) وهي الحالة العملية
 * الأكثر ورود فعلياً. لا يستبدل قفلاً دائماً عبر قاعدة البيانات لو تعددت النسخ
 * مستقبلاً (ذاك إصلاح معماري أكبر، منفصل — انظر PROC-01/durableLease.ts لنمط
 * القفل الدائم المستخدم حالياً للمجدولات الداخلية فقط).
 */

const inFlightReplyKeys = new Set<string>();

/** حد أقصى لعدد المفاتيح المتتبَّعة — يمنع تسرّب ذاكرة نظري لو تعطّل الإفراج. */
const MAX_TRACKED_KEYS = 5000;

/**
 * يبني مفتاح القفل من المنصة ونوع الحدث والمعرّف الخارجي، مع **مفتاح تكرار
 * اختياري** (`idempotencyKey`).
 *
 * الفصل المُصلَح (عطل تسليم المتابعة): كان القفل ومنع التكرار يُفتَّان على
 * `externalId` وحده، فتُصنَّف **متابعة مشروعة** على نفس التعليق (بعد رد أصلي
 * سابق) كـ«رد مكرر» وتُحجب خطأً. الآن `externalId` يبقى للعثور على الهدف، بينما
 * `idempotencyKey` هو مفتاح منع التكرار: متابعة العقل التجاري تأخذ مفتاحاً
 * مميّزاً (`fu1`, `fu2`…) فلا تُحجب، بينما إعادة نفس المفتاح تُحجب كما كان.
 * غياب المفتاح (كل الردود العادية) يُبقي السلوك السابق حرفياً.
 */
export function replyLockKey(platform: string, kind: "comment" | "message", externalId: string, idempotencyKey?: string): string {
  const base = `${String(platform)}:${String(kind)}:${String(externalId)}`;
  const idem = typeof idempotencyKey === 'string' && idempotencyKey.trim() ? idempotencyKey.trim() : '';
  return idem ? `${base}#${idem}` : base;
}

/**
 * يحاول حجز المفتاح. `true` = نجح الحجز (لا طلب آخر قيد التنفيذ لنفس الحدث).
 * مفتاح بلا معرّف خارجي فعلي (فارغ) لا يُقفل — الفحوص الأخرى في المسار تتولى
 * رفضه لسبب آخر (معرّف مطلوب)، فلا نمنح حجزاً زائفاً لمفتاح لا معنى له.
 */
export function acquireReplyLock(key: string): boolean {
  if (!key) return true;
  // نُزيل لاحقة مفتاح التكرار (#…) قبل فحص الفراغ، فلا يُقفل مفتاح بلا معرّف خارجي.
  const withoutIdem = key.includes('#') ? key.slice(0, key.indexOf('#')) : key;
  if (/:(comment|message):$/.test(withoutIdem)) return true;
  if (inFlightReplyKeys.has(key)) return false;
  if (inFlightReplyKeys.size >= MAX_TRACKED_KEYS) return false; // أفضل جهد دفاعي، لا يُفترض بلوغه عملياً
  inFlightReplyKeys.add(key);
  return true;
}

/** يُفرج عن المفتاح — يُستدعى دائماً من `finally` في المستدعي، نجاحاً أو فشلاً. */
export function releaseReplyLock(key: string): void {
  inFlightReplyKeys.delete(key);
}

/** للاختبار فقط: هل المفتاح محجوز حالياً؟ */
export function isReplyLocked(key: string): boolean {
  return inFlightReplyKeys.has(key);
}

/** للاختبار فقط: تفريغ كل الحجوزات (عزل بين حالات الاختبار). */
export function resetReplyLocksForTest(): void {
  inFlightReplyKeys.clear();
}
